#!/usr/bin/env node
// Precomputes the two static lookup tables search_posts() needs to do server-side what
// app/lib/geo.ts currently does client-side: which travel-taxonomy region a country
// belongs to (ISO_TO_REGION), and each country's rough bounding box (for cross-border
// "search 'Alps', match a post tagged France" bbox-overlap matching). Both are derived
// from data already checked into this repo — world-countries' subregion field, and
// app/data/countryBoundaries.json (built by build-country-boundaries.mjs) — so there's
// no live geocoding involved, and nothing here should drift from geo.ts without a
// matching update there. Re-run with `node scripts/build-search-geo-lookup.mjs` any
// time countryBoundaries.json is regenerated or the region taxonomy changes.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { bbox as turfBbox } from "@turf/bbox";
import worldCountries from "world-countries";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BOUNDARIES_PATH = path.join(__dirname, "..", "app", "data", "countryBoundaries.json");
const OUTPUT_PATH = path.join(__dirname, "..", "supabase", "migrations", "0012_search_geo_lookup.sql");

// Mirrors app/lib/geo.ts's SUBREGION_TO_REGION / REGION_FALLBACK / ISO_TO_REGION exactly
// — keep these two in sync by hand if the travel-taxonomy regions ever change.
const SUBREGION_TO_REGION = {
  "Northern Europe": "Europe",
  "Western Europe": "Europe",
  "Southern Europe": "Europe",
  "Eastern Europe": "Europe",
  "Central Europe": "Europe",
  "Southeast Europe": "Europe",
  "North America": "North America",
  "Central America": "North America",
  Caribbean: "North America",
  "South America": "South America",
  "Eastern Asia": "East Asia/SE Asia",
  "South-Eastern Asia": "East Asia/SE Asia",
  "Southern Asia": "East Asia/SE Asia",
  "Central Asia": "East Asia/SE Asia",
  "Western Asia": "Middle East",
  "Australia and New Zealand": "Australia",
  Melanesia: "Australia",
  Micronesia: "Australia",
  Polynesia: "Australia",
  "Northern Africa": "Africa",
  "Eastern Africa": "Africa",
  "Middle Africa": "Africa",
  "Southern Africa": "Africa",
  "Western Africa": "Africa",
};

const REGION_FALLBACK = {
  Americas: "North America",
  Asia: "East Asia/SE Asia",
  Africa: "Africa",
  Europe: "Europe",
  Oceania: "Australia",
};

function sqlString(value) {
  return `'${value.replace(/'/g, "''")}'`;
}

function build() {
  const isoToRegion = {};
  for (const c of worldCountries) {
    const region = SUBREGION_TO_REGION[c.subregion] ?? REGION_FALLBACK[c.region];
    if (region) isoToRegion[c.cca2] = region;
  }

  const boundaries = JSON.parse(fs.readFileSync(BOUNDARIES_PATH, "utf8"));
  const bboxByIso = {};
  for (const f of boundaries.features) {
    bboxByIso[f.properties.iso] = turfBbox(f);
  }

  const isoCodes = Object.keys(isoToRegion).sort();
  const missingBbox = isoCodes.filter((iso) => !bboxByIso[iso]);

  const regionRows = isoCodes.map((iso) => `  (${sqlString(iso)}, ${sqlString(isoToRegion[iso])})`).join(",\n");
  const bboxRows = isoCodes
    .filter((iso) => bboxByIso[iso])
    .map((iso) => {
      const [minLng, minLat, maxLng, maxLat] = bboxByIso[iso];
      return `  (${sqlString(iso)}, ${minLng}, ${minLat}, ${maxLng}, ${maxLat})`;
    })
    .join(",\n");

  const sql = `-- Generated by scripts/build-search-geo-lookup.mjs — do not hand-edit.
-- Static lookup tables mirroring app/lib/geo.ts's ISO_TO_REGION mapping and each
-- country's bounding box (from app/data/countryBoundaries.json), so search_posts()
-- (see 0013_search_posts_rpc.sql) can do the region-containment and cross-border
-- bbox-overlap matching that isGeographicallyRelevant() does client-side today,
-- without any live geocoding on the server.

create table if not exists country_region (
  country_code text primary key,
  region text not null
);

create table if not exists country_bbox (
  country_code text primary key references country_region (country_code),
  min_lng double precision not null,
  min_lat double precision not null,
  max_lng double precision not null,
  max_lat double precision not null
);

insert into country_region (country_code, region) values
${regionRows}
on conflict (country_code) do update set region = excluded.region;

insert into country_bbox (country_code, min_lng, min_lat, max_lng, max_lat) values
${bboxRows}
on conflict (country_code) do update set
  min_lng = excluded.min_lng, min_lat = excluded.min_lat, max_lng = excluded.max_lng, max_lat = excluded.max_lat;
`;

  fs.writeFileSync(OUTPUT_PATH, sql);
  console.log(
    `[build-search-geo-lookup] wrote ${isoCodes.length} country_region rows and ${isoCodes.length - missingBbox.length} country_bbox rows to ${path.relative(process.cwd(), OUTPUT_PATH)}`,
  );
  if (missingBbox.length > 0) {
    console.warn(`[build-search-geo-lookup] no boundary/bbox found for: ${missingBbox.join(", ")} (region row still written, bbox skipped)`);
  }
}

build();
